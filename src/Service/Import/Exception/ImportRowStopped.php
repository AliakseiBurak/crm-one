<?php

declare(strict_types=1);

namespace App\Service\Import\Exception;

/**
 * Строка пакета не сохранена: прогон останавливается на ней.
 *
 * Строка — атомарная единица импорта (design D7): её транзакция откатывается,
 * уже сохранённые строки пакета остаются, а прогон продолжает с последней
 * обработанной позиции. Сообщение называет номер строки в исходном файле и
 * суть проблемы, предлагая два выхода: исправить значение в таблице и
 * утвердить снова либо исправить файл на этой строке и загрузить его заново.
 */
class ImportRowStopped extends \RuntimeException
{
    public function __construct(
        public readonly int $rowNumber,
        string $reason,
    ) {
        parent::__construct(\sprintf(
            'Строка %d не сохранена: %s. Исправьте значение в таблице и утвердите пакет снова '
            . 'либо исправьте файл на этой строке и загрузите его заново — импорт продолжится со строки %d.',
            $rowNumber,
            $reason,
            $rowNumber,
        ));
    }
}
